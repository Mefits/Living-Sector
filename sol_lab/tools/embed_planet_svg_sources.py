#!/usr/bin/env python3
"""Embed the original pilot SVGs as a Godot script resource (stdlib only).

Godot normally raster-imports SVGs and exported PCK files may not contain the
original XML. By embedding them in GDScript we can reliably create DPITexture
zoom tiers in the editor and in Windows builds.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    ("sol/earth", "assets/planets_svg/sol/earth.svg"),
    ("sol/saturn", "assets/planets_svg/sol/saturn.svg"),
    ("biomes/desert_world", "assets/planets_svg/biomes/desert_world.svg"),
]
OUTPUT = ROOT / "scripts/view/planet_svg_sources.gd"

HEADER = '''extends RefCounted
## AUTO-GENERATED by sol_lab/tools/embed_planet_svg_sources.py.
## The embedded source survives Godot exports, which may omit imported .svg
## originals from the PCK. Edit SVG originals, then regenerate this file.

const SOURCES: Dictionary = {
'''
FOOTER = '''}


static func source_for(key: String) -> String:
    return str(SOURCES.get(key, ""))
'''


def main() -> None:
    chunks = [HEADER]
    for key, relpath in SOURCES:
        svg = (ROOT / relpath).read_text(encoding="utf-8").rstrip("\r\n")
        if '"""' in svg or "<svg" not in svg or "</svg>" not in svg:
            raise ValueError("Unsupported SVG source: " + relpath)
        chunks.append(f'    "{key}": """{svg}\n""",\n')
    chunks.append(FOOTER)
    OUTPUT.write_text("".join(chunks), encoding="utf-8")
    print(f"Generated: {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
